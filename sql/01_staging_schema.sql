-- Create staging schema
CREATE SCHEMA IF NOT EXISTS staging;

-- Pipeline observability table (tracks Load Duration, Rows, and Success Status)
CREATE TABLE IF NOT EXISTS staging.pipeline_metrics_batch (
    metric_id SERIAL PRIMARY KEY,
    source_file VARCHAR(100),
    load_start TIMESTAMP,
    load_end TIMESTAMP,
    duration_seconds NUMERIC(10, 4),
    rows_processed INT,
    status VARCHAR(20),
    error_message TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

